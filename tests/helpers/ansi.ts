/**
 * Утилита для тестов терминального вывода.
 *
 * Ink и chalk могут добавлять ANSI-последовательности (цвета, курсор) в вывод.
 * В CI (или при FORCE_COLOR) их наличие не детерминировано, поэтому перед
 * проверками текста последовательности вырезаются — тесты остаются стабильными
 * на любой платформе (Windows/PowerShell/CI).
 */

/** Убирает все ANSI-последовательности (SGR-цвета, курсор, очистку экрана). */
export function stripAnsi(text: string): string {
  // eslint-disable-next-line no-control-regex
  return text.replace(/\u001B\[[0-9;?]*[ -/]*[@-~]/g, '');
}
